export function getAllChapters(): Array<
  ChapterItem & { subjectNameEn: string; subjectNameBn: string; paperNameEn: string; accentColor: string }
> {
  const list: Array<
    ChapterItem & { subjectNameEn: string; subjectNameBn: string; paperNameEn: string; accentColor: string }
  > = [];
  for (const subject of HSC_SCIENCE_SYLLABUS) {
    for (const paper of subject.papers) {
      for (const chapter of paper.chapters) {
        list.push({
          ...chapter,
          subjectNameEn: subject.nameEn,
          subjectNameBn: subject.nameBn,
          paperNameEn: paper.nameEn,
          accentColor: subject.accentColor,
        });
      }
    }
  }
  return list;
}

export function getSubjectById(subjectId: string): SubjectItem | undefined {
  return HSC_SCIENCE_SYLLABUS.find((s) => s.id === subjectId);
}

export function getChapterById(chapterId: string): (ChapterItem & {
  subjectNameEn: string;
  subjectNameBn: string;
  paperNameEn: string;
  accentColor: string;
  activityProfile: SubjectItem["activityProfile"];
}) | undefined {
  for (const subject of HSC_SCIENCE_SYLLABUS) {
    for (const paper of subject.papers) {
      for (const chapter of paper.chapters) {
        if (chapter.id === chapterId) {
          return {
            ...chapter,
            subjectNameEn: subject.nameEn,
            subjectNameBn: subject.nameBn,
            paperNameEn: paper.nameEn,
            accentColor: subject.accentColor,
            activityProfile: subject.activityProfile,
          };
        }
      }
    }
  }
  return undefined;
}

